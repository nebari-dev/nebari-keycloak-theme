import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { expect, test } from "@playwright/test";

/**
 * docs/screenshots.md shows every Nebari login-page baseline. It links the
 * baseline files themselves rather than copies of them, so the docs always show
 * what `main` renders: a rebaseline merged to `main` updates the page with it.
 *
 * What can drift is the list of screenshots on the page. This test renders the
 * page from the baseline directory and fails when the committed copy differs.
 * `npm run test:screenshots:update` rewrites it alongside the baselines.
 */
const theme = "nebari";
const baselineDirectory = new URL(`./screenshots/linux/${theme}/`, import.meta.url);
const galleryFile = new URL("../docs/screenshots.md", import.meta.url);

const imageWidth = 360;

function image(file: string, alt: string): string {
    return `<img src="../tests/screenshots/linux/${theme}/${file}" alt="${alt}" width="${imageWidth}">`;
}

function renderGallery(files: readonly string[]): string {
    const names = new Set(files.map(file => file.replace(/\.png$/, "")));
    // Each preview is `<page>.png` in light mode and `<page>-dark.png` in dark
    // mode; the full-page captures are named for their colour scheme instead.
    const pages = [...names].filter(name => !name.endsWith("-dark") && !name.startsWith("full-page-")).sort();

    const rows = pages.map(page => {
        const light = names.has(page) ? image(`${page}.png`, `${page}, light`) : "";
        const dark = names.has(`${page}-dark`) ? image(`${page}-dark.png`, `${page}, dark`) : "";

        return `| \`${page}\` | ${light} | ${dark} |`;
    });

    return [
        "# Screenshots",
        "",
        "<!-- Generated by tests/screenshot-gallery.spec.ts. Run `npm run test:screenshots:update` to refresh it. -->",
        "",
        "Every login page the `nebari` theme renders, in light and dark mode. These are the baselines the",
        "[screenshot tests](development.md#screenshot-tests) compare against on every pull request, so they show",
        "what `main` renders. The consoles are not covered; see [What CI checks](development.md#what-ci-checks).",
        "",
        "## Full page",
        "",
        "| Light | Dark |",
        "| --- | --- |",
        `| ${image("full-page-light.png", "Sign-in page, light")} | ${image("full-page-dark.png", "Sign-in page, dark")} |`,
        "",
        "## Login pages",
        "",
        "Each capture is cropped to the card. The page name is the `?preview=` value that renders it in the dev server.",
        "",
        "| Page | Light | Dark |",
        "| --- | --- | --- |",
        ...rows,
        ""
    ].join("\n");
}

test("docs/screenshots.md lists every Nebari baseline", () => {
    test.skip(
        process.env.PLAYWRIGHT_CAPTURE_CURRENT === "1",
        "Capture runs render screenshots for review and must not rewrite the docs"
    );

    const files = readdirSync(baselineDirectory).filter(file => file.endsWith(".png"));
    const expected = renderGallery(files);
    const { updateSnapshots } = test.info().config;

    if (updateSnapshots === "all" || updateSnapshots === "changed") {
        writeFileSync(galleryFile, expected);
        return;
    }

    expect(
        readFileSync(galleryFile, "utf8"),
        "docs/screenshots.md is out of date. Run `npm run test:screenshots:update` and commit it."
    ).toBe(expected);
});
